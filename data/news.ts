export function getNewsBySlug(
  slug: string,
): NewsItem | undefined {
  return news.find((item) => item.slug === slug);
}

export function getFeaturedNews(): NewsItem | undefined {
  return news.find((item) => item.featured);
}

export function getLatestNews(limit?: number): NewsItem[] {
  const sortedNews = [...news].sort(
    (a, b) =>
      new Date(b.verifiedAt).getTime() -
      new Date(a.verifiedAt).getTime(),
  );

  if (typeof limit === "number") {
    return sortedNews.slice(0, limit);
  }

  return sortedNews;
}

export function formatNewsDate(
  date: string,
  locale: string = "uz",
): string {
  const dateLocale = locale === "de" ? "de-DE" : "uz-UZ";

  return new Intl.DateTimeFormat(dateLocale, {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date(`${date}T12:00:00`));
}